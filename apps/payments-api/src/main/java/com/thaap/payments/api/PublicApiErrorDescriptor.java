    /**
     * Resolves a published stable code back to its catalogue entry so that no response path can
     * invent retry or recovery semantics that disagree with what the catalogue documents.
     */
    public static java.util.Optional<PublicApiErrorDescriptor> byCode(String code) {
        return java.util.Optional.ofNullable(BY_CODE.get(code));
    }

